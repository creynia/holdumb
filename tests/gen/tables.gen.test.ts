// Preflop table generator (decisions.md D22): `npm run gen:tables` converts the exact C precompute
// (tests/gen/precompute/strat.c → preflop-blind-standard.csv) into the shipped TS table.
// Without GEN_TABLES=1 this file checks that the shipped table is exactly what the CSV encodes.
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { describe, expect, it } from 'vitest';
import { PREFLOP_BLIND_STANDARD } from '../../src/sim/math/tables/preflop-blind-standard';

const here = (p: string) => fileURLToPath(new URL(p, import.meta.url));
const CSV = here('./precompute/preflop-blind-standard.csv');
const OUT = here('../../src/sim/math/tables/preflop-blind-standard.ts');
const COLS = ['SW', 'SL', 'Wq', 'Lq', 'bb2q', 'bb2nq', 'S2x', 'Scp', 'F2', 'Cf'];

/** AA, AKs, AKo, AQs … 22 (the order of the C program's class list). */
const ORDER: string[] = (() => {
  const R = '23456789TJQKA';
  const out: string[] = [];
  for (let h = 12; h >= 0; h--) {
    for (let l = h; l >= 0; l--) {
      if (h === l) out.push(R[h]! + R[l]!);
      else out.push(`${R[h]}${R[l]}s`, `${R[h]}${R[l]}o`);
    }
  }
  return out;
})();

export function encodeRows(csv: string): string {
  const lines = csv.trim().split('\n');
  const head = lines[0]!.split(',');
  const idx = COLS.map((c) => {
    const i = head.indexOf(c);
    if (i < 0) throw new Error(`CSV lacks column ${c}`);
    return i;
  });
  const byName = new Map(lines.slice(1).map((l) => [l.split(',')[0]!, l]));
  if (byName.size !== 169)
    throw new Error(`CSV has ${byName.size} classes, need 169 (still running?)`);
  return ORDER.map((n) => byName.get(n)!)
    .map((line) => {
      const f = line.split(',');
      return `${f[0]}:${idx.map((i) => BigInt(f[i]!).toString(36)).join(',')}`;
    })
    .join(';');
}

export function render(rows: string): string {
  const sha = createHash('sha256').update(rows).digest('hex');
  return `// @generated by npm run gen:tables from tests/gen/precompute/preflop-blind-standard.csv — sha256 ${sha}
// Do not edit. Columns per class (base 36): ${COLS.join(',')} (see src/sim/math/preflop.ts).
import type { BlindPaytableId } from '../../engine/types';

export interface PreflopTable {
  blindPaytable: BlindPaytableId;
  /** Raise path: boards × dealer hands; check path: (flop, turn-river) × dealer hands. */
  denRaise: bigint;
  denCheck: bigint;
  rows: string;
}

export const PREFLOP_BLIND_STANDARD: PreflopTable = {
  blindPaytable: 'blind-standard',
  denRaise: 2_097_572_400n,
  denCheck: 20_975_724_000n,
  rows: '${rows}',
};
`;
}

describe('preflop table generator', () => {
  const csv = readFileSync(CSV, 'utf8');
  const rows = encodeRows(csv);
  if (process.env.GEN_TABLES) {
    it('writes the table', () => {
      writeFileSync(OUT, render(rows));
      expect(rows.split(';')).toHaveLength(169);
    });
  } else {
    it('the shipped table is exactly the encoding of the committed CSV', () => {
      expect(PREFLOP_BLIND_STANDARD.rows).toBe(rows);
      expect(readFileSync(OUT, 'utf8')).toBe(render(rows));
    });
  }
});
